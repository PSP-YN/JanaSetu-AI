import { chromium } from "playwright";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(scriptDir, "assets", "video-raw-final");
const baseUrl = (process.env.JANASETU_DEMO_URL || "https://jana-setu-ai.vercel.app").replace(/\/+$/, "");
await fs.rm(out,{recursive:true,force:true}); await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1920,height:1080},screen:{width:1920,height:1080},deviceScaleFactor:1,recordVideo:{dir:out,size:{width:1920,height:1080}}});
const page=await context.newPage(); page.setDefaultTimeout(10000);
const pause=ms=>page.waitForTimeout(ms);
try {
  await page.goto(`${baseUrl}/`,{waitUntil:"domcontentloaded"});
  await pause(6000);
  await page.locator("#how-it-works").scrollIntoViewIfNeeded().catch(()=>{});
  await pause(3500);
  await page.goto(`${baseUrl}/app`,{waitUntil:"domcontentloaded"});
  await pause(5000);
  await page.getByRole("button",{name:"My profile"}).click();
  const fields=page.locator(".form-grid").first().locator(".field");
  await fields.nth(0).locator("input").fill("Ananya Rao");
  await fields.nth(1).locator("input").fill("34");
  await fields.nth(2).locator("select").selectOption("woman");
  await fields.nth(3).locator("select").selectOption({label:"Karnataka"});
  await fields.nth(4).locator("input").fill("Mysuru");
  await fields.nth(6).locator("input").fill("150000");
  await fields.nth(7).locator("select").selectOption({label:"Farmer"});
  await pause(2500);
  await page.locator(".form-footer .button-primary").click();
  await pause(3500);
  await page.getByRole("button",{name:/Run benefit assessment/}).click();
  await pause(5500);
  await page.getByRole("button",{name:"Find benefits"}).click();
  await pause(3000);
  await page.locator(".search-box input").fill("PM-KISAN");
  await pause(4500);
  await page.getByRole("button",{name:"View details"}).first().click();
  await pause(6500);
  await page.getByRole("button",{name:"Prepare local checklist"}).first().click();
  await pause(5500);
  await page.getByRole("button",{name:"My applications"}).click();
  await pause(7000);
  const proof=(await page.locator("body").innerText()).slice(-1800);
  await fs.writeFile(path.join(scriptDir, "demo-verification.txt"),proof);
  await page.goto(`${baseUrl}/app/automation`,{waitUntil:"domcontentloaded"});
  await pause(6500);
  await page.goto(`${baseUrl}/privacy`,{waitUntil:"domcontentloaded"});
  await pause(5000);
  await page.goto(`${baseUrl}/pitch-deck.html`,{waitUntil:"domcontentloaded"});
  await pause(7000);
} finally { await context.close(); await browser.close(); }
console.log("Recorded final video:",await fs.readdir(out));
